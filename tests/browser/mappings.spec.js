const fs = require('node:fs');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {test,expect} = require('../..');
const root = path.resolve(__dirname,'../fixtures');
const source = fs.readFileSync(path.join(root,'checkout.php'),'utf8');
const line = source.split('\n').findIndex(text => text.includes('BREAKPOINT:'))+1;
test.use({xdebugPathMappings:[{local:'C:\\Site',remote:pathToFileURL(root).href}]});
test('Windows source mapping and debugger APIs work through Linux PHP and Chromium',async ({page,xdebug}) => {
  const action = page.goto('/checkout.php?code=SAVE10',{timeout:0}); action.catch(() => {});
  const session = await xdebug.waitForSession();
  expect(session.info.localFile).toBe('C:\\Site\\checkout.php');
  const point = await session.setBreakpoint('C:\\Site\\checkout.php',line,{hitValue:1,hitCondition:'>='});
  expect((await session.getBreakpoint(point)).localFile).toBe('C:\\Site\\checkout.php');
  await session.updateBreakpoint(point,{state:'disabled'});
  expect((await session.getBreakpoint(point)).state).toBe('disabled');
  await session.updateBreakpoint(point,{state:'enabled'});
  expect(await session.breakpoints()).toHaveLength(1);
  const paused = await session.runUntilBreak(); expect(paused.localFile).toBe('C:\\Site\\checkout.php');
  expect(paused.fileUri).toBe(pathToFileURL(path.join(root,'checkout.php')).href);
  expect((await session.stack())[0].localFile).toBe(paused.localFile);
  expect((await session.status()).status).toBe('break'); expect(await session.stackDepth()).toBeGreaterThan(0);
  expect((await session.contexts())[0]).toBe('Locals');
  expect((await session.featureGet('supports_async')).enabled).toBe(false);
  expect(await session.typeMap()).toEqual(expect.arrayContaining([expect.objectContaining({name:'array',type:'hash'})]));
  expect((await session.source('C:\\Site\\checkout.php',{begin:1,end:3})).toString()).toContain('<?php');
  expect(await session.propertyValue('$binary')).toEqual(Buffer.from([255,0,120]));
  expect((await session.getPropertyPage('$big',{page:2})).children).toHaveLength(50);
  expect(await session.setProperty('$discount','18')).toBe(true);
  expect(await session.evaluate('$discount')).toBe(18);
  await session.removeBreakpoint(point); expect(session.knownBreakpoints[point]).toBeUndefined();
  await session.detach(); expect((await action).status()).toBe(200);
  await expect(page.getByTestId('total')).toHaveText('82');
});
